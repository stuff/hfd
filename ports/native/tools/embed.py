#!/usr/bin/env python3
"""Generates assets.c from the data in rip/, at build time, so that the executable is
self-contained and the repository holds no copy of the data.

usage: embed.py <rip dir> <out.c>

Indexed PNGs become raw palette indices (one byte per pixel, as the web port's
`?indexed` Vite plugin gives them), the pictures' JSON files become a palette and a
sparse list of per-line colours (rasters), and the modules and the text pages' RAM copy
are embedded as they are. Standard library only."""
import json, struct, sys, zlib
from pathlib import Path

rip, out = Path(sys.argv[1]), Path(sys.argv[2])

IMAGES = {
    'IMG_MENU': 'graphics/menu/menu_select_song_indexed.png',
    'IMG_WORD_LOADING': 'graphics/menu/words/word_loading_indexed.png',
    'IMG_WORD_DECRUNCHING': 'graphics/menu/words/word_decrunching_indexed.png',
    'IMG_EAR': 'graphics/pictures/loading_screen_indexed.png',
    'IMG_AURA': 'graphics/pictures/fullscreen/screen_an_aura_production_indexed.png',
    'IMG_HFD': 'graphics/pictures/fullscreen/screen_high_fidelity_dreams_wide_indexed.png',
    'IMG_AEON': 'graphics/pictures/fullscreen/screen_code_and_design_aeon_indexed.png',
}
METAS = {
    'META_EAR': 'graphics/pictures/loading_screen.json',
    'META_AURA': 'graphics/pictures/fullscreen/screen_an_aura_production.json',
    'META_HFD': 'graphics/pictures/fullscreen/screen_high_fidelity_dreams.json',
    'META_AEON': 'graphics/pictures/fullscreen/screen_code_and_design_aeon.json',
}
# Menu order.
SONGS = [
    ('Act of Impulse', '01 - Act of Impulse (Mantronix & Tip).mod'),
    ('Chinese Dream', '02 - Chinese Dream (Firefox & Tip).mod'),
    ('Elysium', '03 - Elysium (Jester).mod'),
    ('Enigma', '04 - Enigma aka Hyperbased (Firefox & Tip).mod'),
    ('Just Spank It', '05 - Just Spank It (Firefox & Tip).mod'),
    ('Macrocosm', '06 - Macrocosm (Firefox) [repaired].mod'),
    ('Overload', '07 - Overload (Mantronix & Tip).mod'),
    ('The Sweat Shop', '08 - The Sweat Shop (Mantronix & Tip).mod'),
]
TEXTPAGE_RAM = 'extracted/textpage/ram_012000_025b00.bin'


def indexed_png(path):
    """Palette indices of an indexed PNG: (width, height, bytes)."""
    data = path.read_bytes()
    assert data[:8] == b'\x89PNG\r\n\x1a\n', path
    pos, idat, ihdr = 8, b'', None
    while pos < len(data):
        n, kind = struct.unpack('>I4s', data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if kind == b'IHDR':
            ihdr = struct.unpack('>IIBBBBB', body)
        elif kind == b'IDAT':
            idat += body
    width, height, depth, color, _, _, interlace = ihdr
    if color != 3 or interlace:
        raise SystemExit(f'{path}: not a non-interlaced indexed PNG')
    raw = zlib.decompress(idat)
    stride = (width * depth + 7) // 8
    rows, prev, p = [], bytearray(stride), 0
    for _ in range(height):  # undo the filters (1 byte per pixel at most)
        f, line = raw[p], bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for i in range(stride):
            a = line[i - 1] if i else 0
            b = prev[i]
            c = prev[i - 1] if i else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + ((a + b) >> 1)) & 255
            elif f == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    mask = (1 << depth) - 1
    pixels = bytearray(width * height)
    for y, line in enumerate(rows):
        for x in range(width):
            bit = x * depth
            pixels[y * width + x] = (line[bit >> 3] >> (8 - depth - (bit & 7))) & mask
    return width, height, bytes(pixels)


def hex_color(c):
    """'#aa8800' (every component a multiple of 17) -> 0xa80, as hex() in the web port."""
    v = int(c[1:], 16)
    return (((v >> 16) & 255) // 17 << 8) | (((v >> 8) & 255) // 17 << 4) | ((v & 255) // 17)


def byte_array(name, data, ctype='uint8_t'):
    lines = [f'static const {ctype} {name}[{max(1, len(data))}] = {{']
    for i in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[i:i + 24]) + ',')
    lines.append('};')
    return '\n'.join(lines)


parts = ['/* Generated by tools/embed.py from rip/. Do not edit. */', '#include "assets.h"', '']
for name, rel in IMAGES.items():
    w, h, px = indexed_png(rip / rel)
    parts.append(byte_array(f'{name.lower()}_data', px))
    parts.append(f'const IndexedImage {name} = {{ {w}, {h}, {name.lower()}_data }};\n')
for name, rel in METAS.items():
    meta = json.loads((rip / rel).read_text())
    pal = ', '.join(f'0x{hex_color(c):03x}' for c in meta['palette'])
    lines = [(y, int(i), hex_color(c)) for y, p in enumerate(meta.get('per_line_palette') or [])
             for i, c in sorted(p.items(), key=lambda kv: int(kv[0])) if c]
    body = ', '.join(f'{{{y}, {i}, 0x{c:03x}}}' for y, i, c in lines) or '{0, 0, 0}'
    parts.append(f'static const uint16_t {name.lower()}_lines[][3] = {{ {body} }};')
    parts.append(f'const PictureMeta {name} = {{ {{ {pal} }}, {name.lower()}_lines, {len(lines)} }};\n')
for k, (title, file) in enumerate(SONGS):
    parts.append(byte_array(f'song{k}_data', (rip / 'music' / file).read_bytes()))
parts.append('const Song SONGS[SONG_COUNT] = {')
for k, (title, file) in enumerate(SONGS):
    parts.append(f'  {{ "{title}", song{k}_data, sizeof song{k}_data }},')
parts.append('};\n')
ram = (rip / TEXTPAGE_RAM).read_bytes()
parts.append(byte_array('textpage_ram', ram))
parts.append('const uint8_t *const TEXTPAGE_RAM = textpage_ram;')
parts.append(f'const size_t TEXTPAGE_RAM_SIZE = {len(ram)};')

out.parent.mkdir(parents=True, exist_ok=True)
text = '\n'.join(parts) + '\n'
if not out.exists() or out.read_text() != text:
    out.write_text(text)
