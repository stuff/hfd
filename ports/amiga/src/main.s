; High Fidelity Dreams, Amiga port.
; The bootblock loads the first part of this program (up to `later`) anywhere in chip
; memory, in BSS_RESERVE bytes of cleared memory more than the whole program: all the
; code is PC-relative, and a5 points to the variables (BSS). The program then loads its
; second part itself (loader.s), while the ear screen shows.
;
; Each VBL, the level 3 interrupt plays the music, then computes the next frame (intro.s)
; into the Copper list that isn't shown, and makes it the next one.

VBLANK_MUSIC	equ	1		; ptplayer: _mt_music is called from our VBL interrupt

; (Assembled from address 0: a label's value is its offset in main.bin.)
	bra.w	start
	dc.l	later			; the first part's size, for the bootblock (see Makefile)
	include	"ptplayer.asm"
	include	"hardware.i"
	include	"memory.i"
	include	"intro.i"		; generated by tools/mkintro.py

; The variables, at the start of the BSS.
	rsreset
v_frames	rs.w	1		; VBL interrupts so far
v_shown		rs.w	1		; the VBL (as in the reference recording) of the next list
v_music		rs.b	1		; non-zero: the music is playing
v_front		rs.b	1		; the Copper buffer shown (0 or 1)
v_screens	rs.b	2		; the screen in each Copper buffer (SCREEN_*, -1 at first)
v_bands		rs.b	4		; the bands' fade levels (0-7), -1: their colour is in v_overrides
v_overrides	rs.w	4
v_vbl		rs.w	1		; the intro's VBL
v_loaded	rs.b	1		; non-zero: the second part is loaded
		rs.b	1
v_load_from	rs.l	1		; loader.s
v_load_to	rs.l	1
v_copper	rs.b	2*COPPER_SIZE	; the two Copper buffers
v_mfm		rs.w	MFM_WORDS	; a track as read from the disk
v_hfd		rs.b	32000		; the second buffer of HIGH FIDELITY DREAMS
BSS_SIZE	rs.b	0

start:
	lea	CUSTOM,a6
	LEAFAR	bss_start,a5
	move.w	#$7fff,INTENA(a6)	; the system is gone from here on
	move.w	#$7fff,INTREQ(a6)
	move.w	#$7fff,INTREQ(a6)
	move.w	#$7fff,DMACON(a6)

	; No sprites: disarm the 8 of them.
	lea	SPR0POS(a6),a0
	moveq	#8-1,d0
.sprite:
	clr.l	(a0)+
	clr.l	(a0)+
	dbf	d0,.sprite

	bsr	intro_init

	lea	level3(pc),a0
	move.l	a0,LEVEL3_VECTOR.w
	sub.l	a0,a0			; vector base: 0 on a 68000
	moveq	#1,d0			; PAL
	bsr	_mt_install
	move.w	#$8380,DMACON(a6)	; DMAEN, BPLEN, COPEN
	move.w	#$c000|INTF_VERTB,INTENA(a6)

	; The second part, after the first on the disk (from sector 2) and in memory.
	move.l	#1024+later,d0
	move.l	#bss_start-later,d1
	LEAFAR	later,a0
	bsr	load_disk
	bsr	intro_loaded
	st	v_loaded(a5)
.idle:	bra.s	.idle

; The VBL interrupt.
level3:
	movem.l	d0-d7/a0-a6,-(sp)
	lea	CUSTOM,a6
	LEAFAR	bss_start,a5
	move.w	#INTF_VERTB,INTREQ(a6)
	move.w	#INTF_VERTB,INTREQ(a6)
	move.w	v_shown(a5),SHOWN_VBL.w
	tst.b	v_music(a5)
	beq.s	.silent
	bsr	_mt_music
.silent:
	bsr	intro_frame
	addq.w	#1,v_frames(a5)
	movem.l	(sp)+,d0-d7/a0-a6
	rte

	include	"intro.s"
	include	"loader.s"

	; The first part's data: the ear.
ear_bitmap:	incbin	"ear.raw"

	; The second part, loaded by the program, from a sector boundary.
	cnop	0,512
later:
aura_bitmap:	incbin	"aura.raw"
hfd_bitmap:	incbin	"hfd.raw"
aeon_bitmap:	incbin	"aeon.raw"
rules:		incbin	"rules.raw"
song:		incbin	"module.mod"

	cnop	0,512
bss_start:

	if	BSS_SIZE>BSS_RESERVE
	fail	"BSS_SIZE is larger than BSS_RESERVE"
	endif
