#!/usr/bin/env python3
"""Converts the demo's data from rip/ for the Amiga port.
usage: mkdata.py <rip dir> <out dir>
Writes ear.raw (the loading screen's ear, 4 bitplanes of 320 × 200, one after the other)
and data.i (its palette and the LOADING pulse, as dc.w lines for main.s)."""
import json, sys
from pathlib import Path
from PIL import Image

rip, out = Path(sys.argv[1]), Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)

pictures = rip / 'graphics/pictures'
ear = Image.open(pictures / 'loading_screen_indexed.png')
w, h = ear.size
pixels = list(ear.getdata())
planes = bytearray()
for plane in range(4):
    for y in range(h):
        for x in range(0, w, 8):
            byte = 0
            for i in range(8):
                byte = byte << 1 | (pixels[y * w + x + i] >> plane & 1)
            planes.append(byte)
(out / 'ear.raw').write_bytes(planes)


def amiga(color: str) -> int:
    """#rrggbb (an STE colour, each component's nibble repeated) to the Amiga's $rgb."""
    v = int(color[1:], 16)
    return (v >> 20 & 0xf) << 8 | (v >> 12 & 0xf) << 4 | (v >> 4 & 0xf)


def pulse(k: int) -> int:
    """LOADING's colour at VBL k of the ear screen (k from 1), as in the web port's intro.ts."""
    m = (k - 1) % 56
    n, sub = m >> 2, m & 3
    up = n < 7
    level = n if up else 7 - (n - 7)
    r, g, b = (level + ((1 if up else -1) if sub >= i else 0) for i in range(3))
    return (r * 2) << 8 | (g * 2) << 4 | b * 2


def words(label: str, values: list[int]) -> str:
    rows = [values[i:i + 8] for i in range(0, len(values), 8)]
    return label + ':\n' + ''.join('\tdc.w\t' + ','.join(f'${v:03x}' for v in row) + '\n' for row in rows)


palette = [amiga(c) for c in json.loads((pictures / 'loading_screen.json').read_text())['palette']]
(out / 'data.i').write_text('; Generated by tools/mkdata.py.\n'
                            + words('ear_palette', palette)
                            + words('pulse_table', [pulse(k) for k in range(1, 57)]))
